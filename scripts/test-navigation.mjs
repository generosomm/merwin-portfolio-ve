import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync('js/studio.js', 'utf8').split('/* Navbar pill:')[1];
assert.ok(source, 'Navbar behavior must be present');
const classes = new Set();
const listeners = {};
const navListeners = {};
const frames = [];
let focused = false;
const nav = { querySelector: () => ({}), querySelectorAll: () => [], classList: { toggle() {} }, contains: () => focused, addEventListener: (key, fn) => navListeners[key] = fn };
const window = { portfolioContentReady: Promise.resolve(), scrollY: 0, visualViewport: null, addEventListener: (key, fn) => listeners[key] = fn };
const root = { classList: { add: x => classes.add(x), remove: x => classes.delete(x), contains: x => classes.has(x) } };
vm.runInNewContext('/* Navbar pill:' + source, { window, document: { querySelector: () => nav, documentElement: root }, matchMedia: () => ({ matches: true }), requestAnimationFrame: fn => { frames.push(fn); return frames.length; }, MutationObserver: class { observe() {} }, ResizeObserver: class { observe() {} } });
await Promise.resolve();
const scroll = y => { window.scrollY = y; listeners.scroll(); while (frames.length) frames.shift()(); };
scroll(200);
assert.equal(classes.has('nav-tucked'), true, 'Touch navbar must release content while scrolling down');
scroll(190); scroll(180);
assert.equal(classes.has('nav-tucked'), false, 'Small upward scrolls accumulate and reveal navigation');
focused = true; scroll(240);
assert.equal(classes.has('nav-tucked'), false, 'Focused navigation must stay visible');
focused = false; classes.add('menu-open'); scroll(300);
assert.equal(classes.has('nav-tucked'), false, 'Open menu must keep its trigger visible');
classes.delete('menu-open'); scroll(360); navListeners.focusin();
assert.equal(classes.has('nav-tucked'), false, 'Keyboard focus reveals tucked navigation');
scroll(0);
assert.equal(classes.has('nav-tucked'), false);
console.log('Navigation checks passed: touch clearance, accumulated scroll return, menu and focus safety.');
