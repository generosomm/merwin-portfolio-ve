import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const source = await readFile('js/content.js', 'utf8');
const html = await readFile('index.html', 'utf8');
assert.equal([...html.matchAll(/id="work"/g)].length, 1, 'Website section must have a unique anchor');
const nodes = new Map();
const context = vm.createContext({ document: { querySelector(selector) {
  if (!nodes.has(selector)) nodes.set(selector, { innerHTML: '', setAttribute() {} });
  return nodes.get(selector);
} } });
vm.runInContext(source.split('window.portfolioContentReady =')[0], context);
context.hero = JSON.parse(await readFile('data/02-hero.json', 'utf8'));
context.work = JSON.parse(await readFile('data/07-work.json', 'utf8'));
context.edits = JSON.parse(await readFile('data/08-edits.json', 'utf8'));
context.chrome = JSON.parse(await readFile('data/01-chrome.json', 'utf8'));
vm.runInContext('renderTopChrome(chrome)', context);
const header = nodes.get('[data-chrome="top"]').innerHTML;
// Centered pill: the main links (menuOnly ones live in the phone menu), no brand, a sound button and a menu button for phones.
assert.doesNotMatch(header, /class="brand"/);
assert.equal([...header.matchAll(/class="chrome-nav-link"/g)].length, context.chrome.nav.links.filter(link => !link.menuOnly).length);
assert.match(header, /class="sound-toggle" type="button" aria-pressed="true"/);
assert.equal([...header.matchAll(/<li class="is-phone">/g)].length, context.chrome.nav.links.filter(link => link.phone).length);
assert.match(header, /class="pill-indicator" aria-hidden="true"/);
assert.match(header, /class="nav-toggle-icon icon-menu"/);
assert.match(header, /class="nav-toggle-icon icon-close"/);
assert.doesNotMatch(header, /class="nav-toggle-label"/);
assert.match(header, /aria-label="Open menu"/);
vm.runInContext('renderHero(hero, chrome)', context);
const markup = nodes.get('[data-section="hero"]').innerHTML;
// The restored original hero: full-width name, portrait, outline twin in front.
assert.match(markup, /class="section-inner hero-inner"/);
assert.match(markup, /id="hero-title"/);
assert.match(markup, /href="#work"/);
assert.match(markup, /View CV/);
assert.match(markup, /class="hero-portrait"/);
assert.match(markup, /class="hero-line-inner hero-line-outline" aria-hidden="true"/);
assert.match(markup, /class="hero-socials"/);
context.experience = JSON.parse(await readFile('data/05-experience.json', 'utf8'));
vm.runInContext('renderExperience(experience)', context);
const experience = nodes.get('[data-section="experience"]').innerHTML;
assert.equal([...experience.matchAll(/class="experience-entry"/g)].length, context.experience.items.length);
assert.match(experience, /<summary class="experience-row">/);
assert.match(experience, /City Government of Sto. Tomas/);
vm.runInContext('renderHero({...hero, portrait: {}}, {})', context);
assert.doesNotMatch(nodes.get('[data-section="hero"]').innerHTML, /src="undefined"/);
vm.runInContext('renderWork(work)', context);
const gallery = nodes.get('[data-section="work"]').innerHTML;
assert.match(gallery, /class="studio-project-image"/);
assert.match(gallery, /Document Tracking/);
assert.doesNotMatch(gallery, /href="null"/);
assert.match(gallery, /class="project-deck"/);
assert.match(gallery, /data-visit-label="Visit live site"/);
assert.ok(context.hero.intro.split(/\s+/).length <= 10, 'Hero copy must stay concise');
assert.equal([...gallery.matchAll(/class="deck-card"/g)].length, context.work.items.filter(item => item.href).length);
assert.match(gallery, /data-deck-step="-1"/);
assert.match(gallery, /data-deck-step="1"/);
const liveCount = context.work.items.filter(item => item.href).length;
assert.match(gallery, /class="deck-thumbs" role="group" hidden aria-label="Jump to a project"/);
assert.equal([...gallery.matchAll(/data-deck-jump="\d+"/g)].length, liveCount, 'Every live site needs a thumbnail');
assert.match(gallery, /data-deck-jump="0" aria-label="ASINTA"/);
assert.doesNotMatch(gallery, /class="project-browser"/);
assert.match(gallery, /class="work-archive"/);
for (const project of context.work.items.filter(item => !item.href && item.image?.src)) {
  assert.ok(!gallery.includes(project.image.src), `Non-live project preview must stay hidden: ${project.title}`);
}
context.numbers = JSON.parse(await readFile('data/04-numbers.json', 'utf8'));
context.practice = JSON.parse(await readFile('data/06-practice.json', 'utf8'));
vm.runInContext('renderNumbers(numbers, {}, work)', context);
const shipped = context.work.items.filter(item => item.title && item.shipped !== false).length;
assert.match(nodes.get('[data-section="numbers"]').innerHTML, new RegExp(`data-count-to="${shipped}">${shipped}<`), 'Shipped count follows the work list');
vm.runInContext('renderNumbers(numbers, {}, {items: [{title: "A"}, {title: "B", shipped: false}]})', context);
assert.match(nodes.get('[data-section="numbers"]').innerHTML, /data-count-to="1">1</);
vm.runInContext('renderPractice(practice)', context);
const services = nodes.get('[data-section="services"]').innerHTML;
assert.doesNotMatch(services, /<img|practice-media|practice-card/, 'Services carry no images or stacked cards');
assert.equal([...services.matchAll(/class="service-object" data-shape="(cube|disc|film)" aria-hidden="true"/g)].length, context.practice.items.length);
assert.equal([...services.matchAll(/class="service-cta" href="#project-brief" data-service="/g)].length, context.practice.items.length);
vm.runInContext('renderPractice({cta: {}, items: [{title: "X", shape: "pyramid"}]})', context);
assert.doesNotMatch(nodes.get('[data-section="services"]').innerHTML, /data-shape="pyramid"|service-cta/, 'Unknown shapes and missing CTA render nothing');
vm.runInContext('renderExperience(experience)', context);
assert.match(nodes.get('[data-section="experience"]').innerHTML, /<summary class="experience-row"><span class="experience-year">\d{4}<\/span><span class="experience-role">[^<]+<\/span><span class="experience-org">/);
console.log('Studio rendering: portrait hero, header, experience disclosures, project deck and non-live preview checks passed.');
